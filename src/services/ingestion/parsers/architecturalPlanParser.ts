export function isArchitecturalFloorPlanText(text: string, fileName: string = ''): boolean {
  const upper = `${fileName}\n${text}`.toUpperCase();
  return (
    upper.includes('TRUMAN COURTHOUSE') ||
    upper.includes('PIPER-WIND ARCHITECTS') ||
    (upper.includes('HISTORICAL SOCIETY') && upper.includes('QUADRANT'))
  );
}

